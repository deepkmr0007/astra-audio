#!/usr/bin/env python3
"""Generates app/src/main/res/values{,-hi}/strings.xml from scripts/strings_source.py
and fails if keys used in Kotlin code are missing, duplicated, or placeholders differ."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from strings_source import S  # noqa: E402


def esc(s: str) -> str:
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s


def placeholders(s: str):
    return sorted(re.findall(r"%\d+\$[sd]", s))


def main() -> int:
    keys = [k for k, _, _ in S]
    dupes = {k for k in keys if keys.count(k) > 1}
    if dupes:
        print("Duplicate keys:", dupes); return 1
    errors = []
    for k, en, hi in S:
        if placeholders(en) != placeholders(hi):
            errors.append(f"{k}: placeholders differ {placeholders(en)} vs {placeholders(hi)}")
        for text in (en, hi):
            # In strings WITH placeholders, a literal percent sign must be written as %%.
            if placeholders(text) and re.search(r"%(?!\d+\$[sd])", text.replace("%%", "")):
                errors.append(f"{k}: unescaped % in a format string")
    used = set()
    for dp, _, files in os.walk(os.path.join(ROOT, "app", "src", "main", "kotlin")):
        for f in files:
            if f.endswith(".kt"):
                used |= set(re.findall(r"R\.string\.([a-z0-9_]+)", open(os.path.join(dp, f), encoding="utf-8").read()))
    missing = used - set(keys)
    if missing:
        errors.append("Missing keys: " + ", ".join(sorted(missing)))
    if errors:
        print("\n".join(errors)); return 1

    for folder, idx in (("values", 1), ("values-hi", 2)):
        out = os.path.join(ROOT, "app", "src", "main", "res", folder, "strings.xml")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as fh:
            fh.write('<?xml version="1.0" encoding="utf-8"?>\n')
            fh.write("<!-- Generated by scripts/gen_strings.py from scripts/strings_source.py. Do not edit by hand. -->\n<resources>\n")
            for row in S:
                k, text = row[0], row[idx]
                attr = ' formatted="false"' if ("%" in text and not placeholders(text)) else ""
                fh.write(f'    <string name="{k}"{attr}>{esc(text)}</string>\n')
            fh.write("</resources>\n")
    unused = set(keys) - used
    print(f"OK: {len(keys)} strings in English and Hindi; {len(used)} used in code" + (f"; unused: {sorted(unused)}" if unused else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
